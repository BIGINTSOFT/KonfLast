export type DocumentTextKey = keyof typeof texts

/** Belge metni; dil verilmezse Türkçe. */
export function documentText(language: DocumentLanguage | null | undefined, key: DocumentTextKey): string {
  return texts[key][language === 'ENGLISH' ? 1 : 0]
}

/**
 * Bir belgeye bağlı kısa yazım: `const t = documentTexts(invoice.documentLanguage)` → `t('invoice')`. `t.lang` belgenin kök öğesine
 * verilir (`<article lang={t.lang}>`): büyük harfe çevrilen başlıklar İngilizce belgede Türkçe kurala (i → İ) göre çevrilmez.
 */
export function documentTexts(language: DocumentLanguage | null | undefined) {
  const t = (key: DocumentTextKey) => documentText(language, key)
  return Object.assign(t, { lang: language === 'ENGLISH' ? 'en' : 'tr' })
}
