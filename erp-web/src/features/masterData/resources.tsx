export interface FieldDef {
  name: string
  label: string
  type: 'text' | 'textarea' | 'number' | 'color' | 'lookup' | 'select' | 'time' | 'date' | 'checkbox' | 'currency'
  required?: boolean
  maxLength?: number
  /** number alanları için adım (ör. SAM için 0.0001). */
  step?: string
  /** lookup alanları için seçilecek kaynağın API adı. */
  lookup?: string
  /** select alanları için seçenekler; ilk seçenek yeni kayıtta varsayılandır. */
  options?: { value: string; label: string }[]
  hint?: string
  /** number alanı boş bırakılabilir; boşsa sunucuya 0 yerine null gönderilir. */
  nullable?: boolean
  /** Yeni kayıtta alanın başlangıç değeri (verilmezse türün boş değeri). */
  defaultValue?: string | boolean
  /** Alanı değiştirmek ayrıca bu yetkiyi ister; yetkisi olmayan kullanıcıda alan salt okunur gösterilir. */
  permission?: string
  /**
   * Kart okuyucu alanı: masaüstü okuyucu klavye gibi kart numarasını yazıp Enter gönderir. Bu alanda Enter
   * formu göndermez; alana girilince içerik seçilir, okutulan kart eski numaranın yerine yazılır.
   */
  scan?: boolean
}

export interface ColumnDef {
  key: string
  label: string
  render?: (row: MasterRow) => ReactNode
  /**
   * Sayısal sütun: sağa yaslanır ve Türkçe sayı biçimiyle yazılır. Sayı verilirse ondalık hane sayısıdır
   * (en az ve en çok); true ise en çok iki hane gösterilir.
   */
  numeric?: boolean | number
  /**
   * Sütun filtresi. Verilmezse metin kutusudur (sayısal sütunda sayı); aynı adlı seçim alanı varsa onun
   * seçenekleri kullanılır. `false` filtreyi kapatır.
   */
  filter?: GridColumn['filter']
}

/** Kayıt kaydedildikten sonra, kaydın Id'siyle çalışan ek işlem; başarısızsa hatayı döner. */
export type AfterSave = (id: number) => Promise<unknown>

export interface FormExtraProps {
  /** Düzenlenen kayıt; yeni kayıtta boştur. */
  row?: MasterRow
  /** Sunucu, standart alanlardan birini reddetti; sekmeli formlar o alanların sekmesine döner. */
  hasFieldErrors: boolean
  /** Sunucunun reddettiği standart alanların adları (sekmeli formlar hatalı alanın sekmesini açar). */
  errorFields: string[]
  /** Formun o anki alan değerleri (alan adıyla). */
  values: Record<string, string | number | boolean | null>
  /** Kaydın standart alanları, alan adıyla; bölüm bunları kendi kısımlarının arasına yerleştirir. */
  fields: Record<string, ReactNode>
  /** Kaydın Aktif / Pasif anahtarı. */
  activeControl: ReactNode
  disabled: boolean
  /** Bölüm, kayıttan sonra yapılacak işi bununla bildirir (yapılacak iş yoksa null). */
  onAfterSaveChange: (action: AfterSave | null) => void
}

