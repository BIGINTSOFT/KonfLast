/** Ekranın simgesi; ayrıntı sayfaları (ör. /shipments/12) listesinin simgesini alır. */
export function navIcon(path: string): LucideIcon {
  const [, first, second] = path.split('/')
  const base = path === '/' ? '/' : `/${first}`
  return itemIcons[`${base}/${second}`] ?? itemIcons[base] ?? ClipboardList
}
